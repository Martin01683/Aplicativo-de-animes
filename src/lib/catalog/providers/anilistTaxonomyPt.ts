export function translateAniListTagName(name: string): string {
  return ANILIST_TAG_PT_TRANSLATIONS[name] || name;
}

export function translateAniListCategory(category: string): string {
  if (!category) return '';
  if (ANILIST_CATEGORY_PT_LABELS[category]) {
    return ANILIST_CATEGORY_PT_LABELS[category];
  }
  const parts = category.split('-');
  return parts.length > 1 ? parts.slice(1).join(' ') : category;
}

export function translateAniListTagDescription(
  name: string,
  fallbackDescription?: string
): string | undefined {
  if (ANILIST_TAG_PT_DESCRIPTIONS[name]) {
    return ANILIST_TAG_PT_DESCRIPTIONS[name];
  }
  const cleanFallback = (fallbackDescription || '').trim();
  return cleanFallback || undefined;
}
